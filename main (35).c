#include <stdio.h>


int findHCF(int a, int b) {
    while (b != 0) {
        int temp = b;
        b = a % b;
        a = temp;
    }
    return a;
}

int main() {
    int num1, num2;

    
    if (scanf("%d %d", &num1, &num2) == 2) {
        
        int hcf = findHCF(num1, num2);
        printf("%d\n", hcf);
    }

    return 0;
}
